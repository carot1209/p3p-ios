#!/usr/bin/env python3
"""Writes a Makefile that builds the P3P runtime, the generated AOT code and a runner.

  gen_make.py --target host|ios --upstream <P3P3DS checkout> --gen <generated AOT dir>
              --out <build dir> [--build-id <text>]

host: a headless test program (runner/host_test.cpp) for Linux/macOS.
ios : the app executable for arm64 iPhoneOS (ios/main.mm), compiled with xcrun.

The upstream source lists are read from cmake/p3p3ds_sources.cmake, so a new
upstream file is picked up without editing this script.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DEFINES = [
    "PSPRECOMP_AOT_PRODUCTION_FASTPATHS=1",
    "PSPRECOMP_NO_FRONTIER_DIAGNOSTICS=1",
    "PSPRECOMP_CHAIN_NOINLINE=1",
    "PSPRECOMP_AOT_ASSUME_NO_WRITE_WATCH=1",
    "NDEBUG",
]


def cmake_list(text, name):
    match = re.search(r"set\(" + name + r"\s+(.*?)\)", text, re.S)
    if not match:
        sys.exit(f"{name} not found in p3p3ds_sources.cmake")
    return [line.strip() for line in match.group(1).splitlines() if line.strip().endswith(".cpp")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", choices=["host", "ios"], required=True)
    ap.add_argument("--upstream", required=True)
    ap.add_argument("--gen", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--build-id", default="dev")
    ap.add_argument("--cxx", default=None)
    ap.add_argument("--min-ios", default="15.0")
    ap.add_argument("--ffmpeg", default=None, help="prefix of a minimal static FFmpeg (include/, lib/): movies are decoded")
    ap.add_argument("--aot-archive", default=None, help="prebuilt libp3p_aot.a: link it instead of compiling the AOT units")
    args = ap.parse_args()

    up = os.path.abspath(args.upstream)
    gen = os.path.abspath(args.gen)
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)

    with open(os.path.join(up, "cmake", "p3p3ds_sources.cmake")) as f:
        text = f.read()
    core = [os.path.join(up, p) for p in cmake_list(text, "P3P3DS_CORE_SOURCES")]
    runtime = [os.path.join(up, p) for p in cmake_list(text, "PSPRECOMP_RUNTIME_SOURCES")]
    aot = sorted(os.path.join(gen, n) for n in os.listdir(gen) if n.endswith(".cpp"))
    if len(aot) < 2:
        sys.exit(f"no generated AOT sources in {gen}")
    runner = [os.path.join(ROOT, "runner", "live_runner.cpp"), os.path.join(ROOT, "runner", "ffmpeg_decoder.cpp"), os.path.join(ROOT, "gpu", "hw_renderer.cpp"),
              os.path.join(ROOT, "gpu", "trace.cpp")]

    includes = [
        os.path.join(up, "core", "include"),
        os.path.join(up, "recomp", "PSPRecomp", "include"),
        os.path.join(up, "profiles", "p3p", "config"),
        os.path.join(ROOT, "runner"),
        os.path.join(ROOT, "gpu"),
    ]
    common = ["-std=c++20", "-O2", "-fno-strict-aliasing"] + ["-D" + d for d in DEFINES] + ["-I" + i for i in includes]
    if args.ffmpeg:
        ff = os.path.abspath(args.ffmpeg)
        common += ["-DP3P_HAVE_FFMPEG=1", "-I" + os.path.join(ff, "include")]
    common.append('-DP3P_BUILD_ID=\\"' + args.build_id + '\\"')
    ldflags = []
    objc_flags = []
    if args.target == "ios":
        cxx = args.cxx or "xcrun -sdk iphoneos clang++"
        platform = ["-arch", "arm64", "-miphoneos-version-min=" + args.min_ios]
        common += platform
        ldflags += platform + ["-framework", "UIKit", "-framework", "Foundation", "-framework", "QuartzCore",
                               "-framework", "CoreGraphics", "-framework", "AudioToolbox", "-framework", "AVFoundation", "-lobjc"]
        objc_flags = ["-fobjc-arc"]
        ldflags += ["-framework", "Metal"]
        main_sources = [os.path.join(ROOT, "ios", "main.mm"), os.path.join(ROOT, "gpu", "metal_backend.mm")]
        product = "P3P"
    else:
        cxx = args.cxx or os.environ.get("CXX", "c++")
        ldflags += ["-pthread"]
        main_sources = [os.path.join(ROOT, "runner", "host_test.cpp"), os.path.join(ROOT, "gpu", "soft_backend.cpp")]
        product = "p3p_host_test"

    if args.ffmpeg:
        ldflags += [os.path.join(ff, "lib", "libavcodec.a"), os.path.join(ff, "lib", "libavutil.a")]
        if args.target == "host":
            ldflags += ["-lm"]
    groups = [("rt", runtime, []), ("core", core, []), ("aot", aot, ["-I" + gen]), ("runner", runner, []),
              ("main", main_sources, objc_flags)]
    lines = ["# Generated by scripts/gen_make.py; do not edit.", "CXX := " + cxx,
             "CXXFLAGS := " + " ".join(common), "LDFLAGS := " + " ".join(ldflags), "", "all: " + product, ""]
    objects = []
    for name, sources, extra in groups:
        if name == "aot" and args.aot_archive:
            continue
        os.makedirs(os.path.join(out, name), exist_ok=True)
        for src in sources:
            obj = os.path.join(name, os.path.splitext(os.path.basename(src))[0] + ".o")
            objects.append(obj)
            lines.append(f"{obj}: {src}")
            lines.append("\t@echo CXX " + os.path.basename(src))
            lines.append("\t@$(CXX) $(CXXFLAGS) " + " ".join(extra) + f" -MMD -MP -c {src} -o {obj}")
            lines.append("")
    # The AOT objects go into an archive of their own: CI caches it, because it
    # only changes with the EBOOT, the upstream code generator and the flags.
    aot_objects = [o for o in objects if o.startswith("aot/")]
    other_objects = [o for o in objects if not o.startswith("aot/")]
    if args.aot_archive:
        lines.append("libp3p_aot.a: " + os.path.abspath(args.aot_archive))
        lines.append("\t@cp $< $@")
    else:
        lines.append("libp3p_aot.a: " + " ".join(aot_objects))
        lines.append("\t@rm -f $@")
        lines.append("\t@ar rcs $@ $^")
    lines.append("")
    lines.append(f"{product}: {' '.join(other_objects)} libp3p_aot.a")
    # Every AOT unit registers itself through generated_registry.cpp, which the
    # runner references, so a plain archive link pulls all of them in.
    lines.append(f"\t$(CXX) -o $@ {' '.join(other_objects)} libp3p_aot.a $(LDFLAGS)")
    lines.append("")
    lines.append("-include $(wildcard */*.d)")
    with open(os.path.join(out, "Makefile"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}/Makefile: {len(runtime)} runtime, {len(core)} core, {len(aot)} AOT sources -> {product}")


if __name__ == "__main__":
    main()
